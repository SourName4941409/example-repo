
# This program demonstrates type conversion in Python. It converts a float to an integer, an integer to a float, an integer to a string, and a string to an integer.

# Stored variables of different data types
num1 = 99.23
num2 = 23
num3 = 150
string1 = "100"

# Convert num1 to an integer, num2 to a float, num3 to a string, and string1 to an integer
int_num1 = int(num1)
float_num2 = float(num2)
string_num3 = str(num3)
int_string1 = int(string1)

# Print the converted values and their data types
print(int_num1)
print(type(int_num1))

print()
print(float_num2)
print(type(float_num2))

print()
print(string_num3)
print(type(string_num3))

print()
print(int_string1)
print(type(int_string1))
